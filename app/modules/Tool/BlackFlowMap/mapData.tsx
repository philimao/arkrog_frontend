export interface MapShorthand {
  id: string;
  zone: string;
  rows: number;
  cols: number;
  start: [number, number]; // [r, c]
  ends?: [number, number][]; // [[r, c], ...]
  battleEnd?: [number, number]; // [[r, c], ...]
  edges: [number, number, number, number][]; // [r1, c1, r2, c2]
  notes?: string;
  knownBattles?: [number, number][];
  knownShops?: [number, number][];
}

export function toGridState(m: MapShorthand): GridState {
  const connections: GridState["connections"] = {};
  for (const [r1, c1, r2, c2] of m.edges) {
    const key = edgeKey(nodeId(r1, c1), nodeId(r2, c2));
    connections[key] = { active: true };
  }
  return { rows: m.rows, cols: m.cols, connections };
}

